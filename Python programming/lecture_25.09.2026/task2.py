n = int(input("Введите число: "))

if n % 2 == 0:
    print(n, "- четное число")
else:
    print(n, "- нечетное число")
if n > 0:
    print(n, "- положительное число")
elif n < 0:
    print(n, "- отрицательное число")
else:
    print(n, "- ноль")
if 10 <= n <= 50:
    print(n, " находится в диапазоне от 10 до 50")
